// Generates REUSE.toml and the LicenseRef texts in LICENSES/ from
// lib/licence-scope.ts and lib/attribution.ts, so the machine-readable licence
// split and the prose the site renders cannot disagree.
//
//   pnpm reuse           rewrite REUSE.toml and LICENSES/LicenseRef-*.txt
//   pnpm reuse:check     fail if any of them is stale (run in CI)
//
// LICENSES/MIT.txt and LICENSES/CC-BY-SA-3.0.txt are NOT generated. They are
// the verbatim SPDX texts and are committed as fetched — never reflowed.
//
// Requires Node's --experimental-strip-types; both lib modules are dependency
// free precisely so they can be loaded this way.

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const { NON_AFFILIATION_NOTICE, RIGHTS_CONTACT, WOTC_NOTICE } = await import('../lib/attribution.ts');
const { LICENCE_EXCEPTIONS, PROJECT_COPYRIGHT, PROJECT_LICENCE } = await import('../lib/licence-scope.ts');

const root = path.join(import.meta.dirname, '..');

/** TOML basic string. Only backslash and double quote need escaping here. */
const str = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** A single string stays scalar; several become a TOML array. */
const paths = (list) => (list.length === 1 ? str(list[0]) : `[${list.map(str).join(', ')}]`);

// The catch-all comes first and the exceptions after it, so the more specific
// annotation is the last one matching any excluded path. `precedence` is left
// at its default: no file in this repository carries an SPDX header or a
// .license file, so there is nothing closer for an override to beat.
const REUSE_TOML = `# Generated from lib/licence-scope.ts by scripts/gen-reuse.mjs.
# Edit that module, then run \`pnpm reuse\`.
#
# MIT covers this repository EXCEPT the paths annotated below. New directories
# therefore default to permissive. The prose version of this split is in NOTICE.

version = 1

[[annotations]]
path = "**"
SPDX-FileCopyrightText = ${str(PROJECT_COPYRIGHT)}
SPDX-License-Identifier = ${str(PROJECT_LICENCE)}
${LICENCE_EXCEPTIONS.map(
    (e) => `
# ${e.label}
[[annotations]]
path = ${paths([...e.paths])}
SPDX-FileCopyrightText = ${str(e.copyright)}
SPDX-License-Identifier = ${str(e.spdxId)}
`,
).join('')}`;

const WOTC_TEXT = `Wizards of the Coast Fan Content Policy
=======================================

This file is generated by scripts/gen-reuse.mjs. It is not a licence granted by
this project. It records the terms under which material owned by Wizards of the
Coast LLC appears in this repository.

${WOTC_NOTICE}

${NON_AFFILIATION_NOTICE}

The policy itself:

    https://company.wizards.com/en/legal/fancontentpolicy

Two things follow from it for anyone reusing this repository:

  * It is permission rather than a licence, and Wizards of the Coast may
    withdraw it at any time.
  * It requires that the content stay free to access — no paywall, no
    subscription, no gated download. If you fork this, that applies to you too.

Cutting a tile pyramid out of the artwork, or screenshotting it, produces no new
rights in the picture. The MIT licence in LICENSE reaches none of it.
`;

const UNTRACEABLE_TEXT = `Untraceable origin
==================

This file is generated by scripts/gen-reuse.mjs. It is not a licence. It is a
statement that this project does not know who owns the material it is applied
to, and therefore cannot license that material to you.

Applies to the marker data in public/data/Faerun/*.json: 297 place names with
the pixel coordinates that locate them on the map.

This project did not compile that data. It came from a forum that went offline
years ago — the domain now serves an unrelated site, and the data has circulated
since with no attribution attached to it. Whoever assembled it cannot be
identified from what survives.

So:

  * Nothing here asserts any claim over it, and this project grants no
    permission over it. The MIT licence in LICENSE does not extend to it.
  * It is recorded as untraceable rather than quietly folded into the MIT
    grant, because granting rights this project does not hold would be the
    worse error.

If you compiled this data, or you know who did, please say so and it will be
credited or removed, whichever you prefer.

Publicly:

    ${RIGHTS_CONTACT.public}

Privately:

    ${RIGHTS_CONTACT.private}
`;

// Keyed by SPDX id so the LICENSES/ filename is derived rather than repeated —
// REUSE requires the file be named exactly for the identifier it defines, and a
// rename in lib/licence-scope.ts would otherwise silently orphan the text.
const LICENSE_REF_TEXTS = {
    'LicenseRef-WotC-Fan-Content': WOTC_TEXT,
    'LicenseRef-Untraceable-Origin': UNTRACEABLE_TEXT,
};

const declared = LICENCE_EXCEPTIONS.map((e) => e.spdxId).filter((id) => id.startsWith('LicenseRef-'));
const missing = declared.filter((id) => !(id in LICENSE_REF_TEXTS));
if (missing.length) {
    console.error(`No LICENSES/ text defined for: ${missing.join(', ')}`);
    process.exit(1);
}

const outputs = [
    ['REUSE.toml', REUSE_TOML],
    ...declared.map((id) => [`LICENSES/${id}.txt`, LICENSE_REF_TEXTS[id]]),
];

const check = process.argv.includes('--check');
let stale = false;

for (const [rel, content] of outputs) {
    const file = path.join(root, rel);
    if (check) {
        const current = await readFile(file, 'utf8').catch(() => '');
        if (current !== content) {
            console.error(`${rel} is out of date. Run \`pnpm reuse\`.`);
            stale = true;
        }
    } else {
        await writeFile(file, content, 'utf8');
        console.log(`Wrote ${file}`);
    }
}

if (check) {
    if (stale) process.exit(1);
    console.log('REUSE.toml and LICENSES/LicenseRef-*.txt are up to date.');
}
